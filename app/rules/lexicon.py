import re
from dataclasses import dataclass


@dataclass
class Rule:
    pattern: re.Pattern
    category: str
    severity: str  # high | medium
    message: str


@dataclass
class AbsenceRule:
    """맥락 패턴이 있는데 필수 패턴이 없으면 탐지 — 표기 의무 규정용"""
    context_pattern: re.Pattern
    required_pattern: re.Pattern
    category: str
    severity: str  # high | medium
    message: str


def _p(expr: str) -> re.Pattern:
    return re.compile(expr)


